-- Passive all-operator identity evidence captured from already-fetched Tourvisor search rows.
-- No extra Tourvisor calls. Safe to apply independently before deploying observer code.
CREATE TABLE IF NOT EXISTS tour_operator_identity_observations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    fingerprint CHAR(64) NOT NULL,
    first_seen_at DATETIME NOT NULL,
    last_seen_at DATETIME NOT NULL,
    observation_count INT UNSIGNED NOT NULL DEFAULT 1,
    source VARCHAR(40) NOT NULL DEFAULT 'user_search',
    search_id BIGINT UNSIGNED DEFAULT NULL,
    country_id INT UNSIGNED NOT NULL,
    region_id INT UNSIGNED DEFAULT NULL,
    subregion_id INT UNSIGNED DEFAULT NULL,
    hotel_id INT UNSIGNED NOT NULL,
    hotel_name VARCHAR(255) DEFAULT NULL,
    region_name VARCHAR(180) DEFAULT NULL,
    subregion_name VARCHAR(180) DEFAULT NULL,
    latitude DECIMAL(10,7) DEFAULT NULL,
    longitude DECIMAL(10,7) DEFAULT NULL,
    operator_id INT UNSIGNED NOT NULL,
    operator_name VARCHAR(180) DEFAULT NULL,
    tour_id VARCHAR(220) NOT NULL,
    operator_link VARCHAR(2048) NOT NULL,
    operator_link_host VARCHAR(255) NOT NULL,
    operator_link_path VARCHAR(1200) NOT NULL,
    operator_link_query VARCHAR(1200) DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_operator_identity_fingerprint (fingerprint),
    KEY idx_operator_identity_hotel_operator (hotel_id, operator_id, last_seen_at),
    KEY idx_operator_identity_operator_hotel (operator_id, hotel_id, last_seen_at),
    KEY idx_operator_identity_country_seen (country_id, last_seen_at),
    KEY idx_operator_identity_host_seen (operator_link_host, last_seen_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
