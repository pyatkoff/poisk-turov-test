const assert = require('node:assert/strict');
const { packagesFromDryRun, inspectDependencies } = require('../scripts/ci/search3_visual_browser_dependencies.cjs');

const cli = '/fixture/playwright';
const packages = ['libasound2t64', 'libx11-6', 'fonts-noto-color-emoji', 'xvfb'];
const printed = 'sudo -- sh -c "apt-get update&& apt-get install -y --no-install-recommends ' + packages.join(' ') + '"\n';
const installed = packages.map(pkg => `${pkg}\tinstall ok installed`).join('\n') + '\n';
const ok = stdout => ({ status: 0, stdout, stderr: '' });

function check(overrides = {}, platform = 'linux') {
  const calls = [];
  const run = (command, args, options) => {
    calls.push({ command, args });
    assert.equal(options.timeout, 30000);
    assert.deepEqual(options.stdio, ['ignore', 'pipe', 'pipe']);
    if (args[0] === '--version') {
      assert.equal(command, cli);
      return overrides.version || ok('Version 1.55.0\n');
    }
    if (args[0] === 'install-deps') {
      assert.equal(command, cli);
      assert.deepEqual(args, ['install-deps', '--dry-run', 'chromium']);
      return overrides.dryRun || ok(printed);
    }
    assert.equal(command, 'dpkg-query');
    assert.deepEqual(args, ['--show', '--showformat=${Package}\t${Status}\n', '--', ...packages]);
    return overrides.query || ok(installed);
  };
  return { result: inspectDependencies(cli, run, platform), calls };
}

for (const envelope of ['sh -c', 'sudo -- sh -c', 'su root -c'])
  assert.deepEqual(packagesFromDryRun(printed.replace('sudo -- sh -c', envelope)), packages);
for (const unexpected of ['', printed + 'echo extra', printed.replace('xvfb', 'xvfb;touch /tmp/unsafe'), printed.replace('xvfb', '$(id)'), printed.replace('xvfb', '-y'), printed.replace('xvfb', 'xvfb xvfb'), printed.replace('&& ', '; ')])
  assert.equal(packagesFromDryRun(unexpected), null, 'unknown shell text must never become executable input');

const ready = check();
assert.equal(ready.result.ready, true);
assert.equal(ready.result.package_count, packages.length);
assert.equal(ready.calls.length, 3);
const rejected = [
  { version: ok('Version 1.56.0') },
  { version: { status: 1, stdout: '', stderr: '' } },
  { dryRun: { status: 1, stdout: printed, stderr: '' } },
  { dryRun: { ...ok(printed), stderr: 'Unsupported OS fallback' } },
  { dryRun: ok('apt-get install chromium') },
  { query: { status: 1, stdout: installed, stderr: 'missing package' } },
  { query: ok(installed.replace('install ok installed', 'deinstall ok config-files')) },
  { query: ok(installed.replace('install ok installed', 'install ok unpacked')) },
  { query: ok(installed.split('\n').slice(1).join('\n')) },
  { query: ok(installed + 'extra\tinstall ok installed\n') },
  { query: ok(installed.replace('libasound2t64', 'libx11-6')) },
  { query: { ...ok(installed), signal: 'SIGTERM' } },
  { query: { ...ok(installed), error: new Error('query timeout') } },
];
for (const fixture of rejected) assert.equal(check(fixture).result.ready, false);
assert.equal(check({}, 'darwin').result.ready, false);
assert.equal(check({}, 'darwin').calls.length, 0);
assert.equal(inspectDependencies(cli, () => { throw new Error('spawn unavailable'); }, 'linux').ready, false);

// Only dry-run, version and dpkg queries are possible here. A negative decision
// delegates to the unchanged required installer in the workflow, never a shell
// command generated by the dry run. Real installer/browser failures stay fatal.
for (const call of ready.calls) assert(!call.args.includes('install'));
console.log('PASS Chromium dependency preflight: full libraries/fonts/tools, strict command parsing, 15 unknown/missing/failure cases fail closed');
