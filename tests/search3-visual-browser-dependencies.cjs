function mirrorFixture(options = {}) {
  const calls = [], state = { content: options.content ?? stockMirrors, temporary: undefined };
  const metadata = () => ({ dev: 1, ino: 22, mode: 0o100640, uid: 0, gid: 88,
    size: Buffer.byteLength(state.content), mtimeMs: 42,
    isFile: () => !options.symlink && !options.directory,
    isSymbolicLink: () => !!options.symlink });
  let lstatCount = 0;
  const record = (name, args) => {
    calls.push({ name, args });
    if (options.fail === name) throw Object.assign(new Error('fixture filesystem failure'), { code: options.code || 'EIO' });
  };
  const io = {
    lstatSync(...args) {
      record('lstat', args); lstatCount++;
      const stat = metadata();
      if (options.race && lstatCount === 2) stat.ino++;
      return stat;
    },
    openSync(...args) { record('open', args); if (options.collision && args[0] !== MIRROR_FILE) throw Object.assign(new Error('existing temporary path'), { code: 'EEXIST' }); return args[0] === MIRROR_FILE ? 11 : 12; },
    fstatSync(...args) { record('fstat', args); const stat = metadata(); if (options.readRace) stat.ino++; return stat; },
    readFileSync(...args) { record('read', args); return state.content; },
    fchownSync(...args) { record('chown', args); },
    fchmodSync(...args) { record('chmod', args); },
    writeFileSync(...args) { record('write', args); state.temporary = args[1]; },
    fsyncSync(...args) { record('fsync', args); },
    closeSync(...args) { record('close', args); },
    renameSync(...args) { record('rename', args); state.content = state.temporary; state.temporary = undefined; },
    unlinkSync(...args) { record('unlink', args); state.temporary = undefined; },
  };
  const isTemporary = name => /^\/etc\/apt\/apt-mirrors\.txt\.search3-\d+-0123456789abcdef$/.test(name);
  const execute = (uid = 0) => {
    try { return preferUbuntuMirror(io, uid, () => '0123456789abcdef'); }
    finally {
      // Outside the helper's catch: even error fixtures must prove that every
      // read/write/rename/cleanup stays on the fixed file or its own temp file.
      for (const call of calls) {
        if (call.name === 'lstat') assert.equal(call.args[0], MIRROR_FILE);
        if (call.name === 'open') assert(call.args[0] === MIRROR_FILE || isTemporary(call.args[0]));
        if (['fstat', 'read'].includes(call.name)) assert.equal(call.args[0], 11);
        if (['chown', 'chmod', 'write', 'fsync'].includes(call.name)) assert.equal(call.args[0], 12);
        if (call.name === 'rename') { assert(isTemporary(call.args[0])); assert.equal(call.args[1], MIRROR_FILE); }
        if (call.name === 'unlink') assert(isTemporary(call.args[0]));
        if (call.name === 'close') assert([11, 12].includes(call.args[0]));
      }
    }
  };
  return { state, calls, execute };
}
