const assert = require('node:assert/strict');
const { packagesFromDryRun, inspectDependencies, preferredMirrorList, preferUbuntuMirror, MIRROR_FILE } = require('../scripts/ci/search3_visual_browser_dependencies.cjs');

const cli = '/fixture/playwright';
const packages = ['libasound2t64', 'libx11-6', 'fonts-noto-color-emoji', 'xvfb'];
const printed = 'sudo -- sh -c "apt-get update&& apt-get install -y --no-install-recommends ' + packages.join(' ') + '"\n';
const installed = packages.map(pkg => `${pkg}\tinstall ok installed`).join('\n') + '\n';
const ok = stdout => ({ status: 0, stdout, stderr: '' });

function check(overrides = {}, platform = 'linux') {
  const calls = [];
  const run = (command, args, options) => {
    calls.push({ command, args });
    assert.equal(options.timeout, 30000);
    assert.deepEqual(options.stdio, ['ignore', 'pipe', 'pipe']);
    if (args[0] === '--version') {
      assert.equal(command, cli);
      return overrides.version || ok('Version 1.55.0\n');
    }
    if (args[0] === 'install-deps') {
      assert.equal(command, cli);
      assert.deepEqual(args, ['install-deps', '--dry-run', 'chromium']);
      return overrides.dryRun || ok(printed);
    }
    assert.equal(command, 'dpkg-query');
    assert.deepEqual(args, ['--show', '--showformat=${Package}\t${Status}\n', '--', ...packages]);
    return overrides.query || ok(installed);
  };
  return { result: inspectDependencies(cli, run, platform), calls };
}

