'use strict';
const assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const { classify, SOURCE, OUTPUT, IMPORT } = require('../scripts/build/search3-js/presentation-scope.cjs');
const paths = [SOURCE, OUTPUT, IMPORT];
const before = 'body.search3-candidate{color:black;& .hotel-body{padding:18px}@media(max-width:760px){& .hotel-offers-summary{gap:14px}& .search3-shortlist{gap:18px}}}';
function files(source, output = source, extra = {}) {
  return { [SOURCE]: source, [OUTPUT]: output, [IMPORT]: JSON.stringify({ assets: {
    'search3-results-filters-v1.css': { candidateSha256: 'retained', productionSha256: createHash('sha256').update(output).digest('hex') }
  }, ...extra }) };
}
function check(source, expected, changed = paths) {
  const a = files(before), b = files(source);
  const result = classify(changed, p => a[p], p => b[p]);
  assert.equal(result.cardOnly, expected, `${source}: ${result.reason}`);
}
check(before.replace('padding:18px', 'padding:12px').replace('gap:14px', 'gap:8px'), true);
check(before.replace('color:black', 'color:red'), false);
check(before.replace('gap:18px', 'gap:8px'), false);
check(before.replace('760px', '800px'), false);
check(before.replace('& .hotel-body', '& .hotel-body,.search3-shortlist'), false);
check(before.replace('& .hotel-body', '& .hotel-body + .search3-shortlist'), false);
check(before.replace('& .hotel-body', '& .hotel-body ~ .search3-shortlist'), false);
check(before.replace('padding:18px', 'padding:12px;& + .search3-shortlist{display:none}'), false);
check(before.replace('& .hotel-body{padding:18px}', '& #tourDetails{& .hotel-body{padding:12px}}'), false);
check(before.replace('color:black', 'color:black;@font-face{font-family:changed;src:url(font)}'), false);
check(before.replace('padding:18px', 'padding:12px'), false, [...paths, 'v2/results-renderer-v5.js']);
check(before, false, [SOURCE, OUTPUT]);
check(before, false, [OUTPUT, IMPORT]);
check('invalid {{{', false);
const a = files(before), b = files(before, 'generated', { status: 'changed' });
assert.equal(classify(paths, p => a[p], p => b[p]).cardOnly, false, 'metadata is not a CSS hash');
b[IMPORT] = a[IMPORT];
assert.equal(classify(paths, p => a[p], p => b[p]).cardOnly, false, 'unmatched generated bytes fail closed');
assert.equal(classify(paths, () => { throw new Error('missing ref'); }, p => b[p]).cardOnly, false);
const current = fs.readFileSync(path.join(__dirname, '..', SOURCE), 'utf8');
const changed = current.replace('& .hotel-body{padding:16px 18px}', '& .hotel-body{padding:12px 16px}');
assert.notEqual(current, changed, 'exercise an actual current card rule');
const baseline = files(current), candidate = files(changed);
assert.equal(classify(paths, p => baseline[p], p => candidate[p]).cardOnly, true, 'current nested card stylesheet is supported');
